#!/usr/bin/env python3
"""Modification 1: common-subexpression elimination (CSE) for the constant GF(2^16)
multiplier bank of the SSEC decoder.

All constant multiplications in the location/magnitude unit share ONE input, S1:
    location  : S1 * a^i        i = 0..18   (17 data + 2 parity positions)
    magnitude : S1 * a^-i       i = 0..18
Each product bit is an XOR of some S1 bits, so the whole bank is one 16-input
linear map with 38*16 = 608 outputs. Paar's greedy algorithm repeatedly extracts
the XOR pair shared by the most outputs, then each output is finished with a
balanced XOR tree. The script writes rtl/gf16_cmul_bank_cse.v and prints the
XOR2 count before/after.

Usage: python3 gen_cse.py ../rtl/gf16_cmul_bank_cse.v
"""
import sys, itertools, collections, json
import gf16

POS = list(range(19))
CONSTS = [gf16.apow(i) for i in POS] + [gf16.apow(-i) for i in POS]

outs = []
for c in CONSTS:
    outs += [set(r) for r in gf16.const_matrix(c)]

naive = sum(max(len(o) - 1, 0) for o in outs)
naive_depth = max((len(o) - 1).bit_length() for o in outs if o)

# ---------------------------------------------------------------- Paar CSE
nsig = 16
defs = {}                          # new signal -> (a, b)
level = {i: 0 for i in range(16)}
work = [set(o) for o in outs]
while True:
    cnt = collections.Counter()
    for o in work:
        if len(o) >= 2:
            for p in itertools.combinations(sorted(o), 2):
                cnt[p] += 1
    if not cnt:
        break
    # most frequent pair; tie-break on lowest resulting level (keeps depth down)
    best = max(cnt.items(), key=lambda kv: (kv[1], -max(level[kv[0][0]], level[kv[0][1]])))
    (a, b), f = best
    if f < 2:
        break
    t = nsig; nsig += 1
    defs[t] = (a, b); level[t] = max(level[a], level[b]) + 1
    for o in work:
        if a in o and b in o:
            o.discard(a); o.discard(b); o.add(t)

shared = len(defs)
# finish each output with a balanced tree (depth-aware: pair the shallowest first)
final_x = 0
depth = 0
out_expr = []
for o in work:
    terms = sorted(o, key=lambda s: level[s])
    lv = [level[s] for s in terms]
    names = ["t%d" % s if s >= 16 else "s1[%d]" % s for s in terms]
    if not names:
        out_expr.append(("1'b0", 0)); continue
    while len(names) > 1:
        # combine the two shallowest
        i = sorted(range(len(names)), key=lambda k: lv[k])[:2]
        a, b = i
        nm = "(%s ^ %s)" % (names[a], names[b]); nl = max(lv[a], lv[b]) + 1
        final_x += 1
        for k in sorted(i, reverse=True):
            names.pop(k); lv.pop(k)
        names.append(nm); lv.append(nl)
    out_expr.append((names[0], lv[0])); depth = max(depth, lv[0])

total = shared + final_x
stats = {"outputs": len(outs), "naive_xor2": naive, "naive_depth": naive_depth,
         "cse_shared_xor2": shared, "cse_final_xor2": final_x, "cse_total_xor2": total,
         "cse_depth": depth, "reduction_pct": round(100.0 * (naive - total) / naive, 1)}

# ---------------------------------------------------------------- emit Verilog
NC = len(CONSTS)
L = []
L.append("// Auto-generated by scripts/gen_cse.py  -- do not edit by hand")
L.append("// Modification 1: shared constant-GF(2^16) multiplier bank with CSE")
L.append("//   prod[16*i +: 16]        = s1 * a^i    (i = 0..18, error-location products)")
L.append("//   prod[16*(19+i) +: 16]   = s1 * a^-i   (i = 0..18, error-magnitude products)")
L.append("// XOR2 gates : naive %d  ->  CSE %d  (%.1f%% fewer), logic depth %d -> %d"
         % (naive, total, stats["reduction_pct"], naive_depth, depth))
L.append("// Field polynomial x^16 + x^12 + x^3 + x + 1")
L.append("`timescale 1ns / 1ps")
L.append("module gf16_cmul_bank_cse (")
L.append("    input  wire [15:0]        s1,")
L.append("    output wire [%d:0]       prod" % (16 * NC - 1))
L.append(");")
for t in sorted(defs):
    a, b = defs[t]
    na = "t%d" % a if a >= 16 else "s1[%d]" % a
    nb = "t%d" % b if b >= 16 else "s1[%d]" % b
    L.append("    wire t%d = %s ^ %s;" % (t, na, nb))
for k, (e, _) in enumerate(out_expr):
    L.append("    assign prod[%d] = %s;" % (k, e))
L.append("endmodule")
open(sys.argv[1] if len(sys.argv) > 1 else "gf16_cmul_bank_cse.v", "w").write("\n".join(L) + "\n")
json.dump(stats, open("cse_stats.json", "w"), indent=1)
print(json.dumps(stats, indent=1))
